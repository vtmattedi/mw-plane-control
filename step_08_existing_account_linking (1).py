def run(cmd: list[str], cwd: Path) -> None:
    print("+", " ".join(cmd))
    subprocess.run(cmd, cwd=cwd, check=True, text=True)


def backup(root: Path, path: Path, backup_dir: Path) -> None:
    if not path.exists() or not path.is_file():
        return
    target = backup_dir / path.relative_to(root)
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists():
        shutil.copy2(path, target)


def ensure_gitignore(root: Path, backup_dir: Path | None, dry_run: bool) -> None:
    path = root / ".gitignore"
    if not path.is_file():
        fail("missing expected file: .gitignore")

    original = path.read_text(encoding="utf-8")
    lines = original.splitlines()
    normalized: list[str] = []
    found = False
    for line in lines:
        if line.strip() in {".backup/", ".backups/"}:
            if not found:
                normalized.append(".backup/")
                found = True
            continue
        normalized.append(line)
    if not found:
        if normalized and normalized[-1].strip() != "":
            normalized.append("")
        normalized.append(".backup/")

    updated = "\n".join(normalized).rstrip() + "\n"
    if updated == original:
        return

    if dry_run:
        print("  patch: .gitignore -> .backup/")
        return

    assert backup_dir is not None
    backup(root, path, backup_dir)
    path.write_text(updated, encoding="utf-8", newline="\n")
    print("patched: .gitignore -> .backup/")


def validate(root: Path, args: argparse.Namespace) -> None:
    for rel in REQUIRED:
        if not (root / rel).is_file():
            fail(
                f"missing Step 07 prerequisite: {rel}. "
                "Run this from the mw-plane-control repository root after Step 07."
            )

    roadmap = (root / "docs/implementation-roadmap.md").read_text(encoding="utf-8")
    if ROADMAP_MARKER not in roadmap:
        fail(
            "docs/implementation-roadmap.md does not contain the expected "
            "Step 08 existing-account-linking section."
        )

    step7 = (root / "scripts/e2e-step-07.ps1").read_text(encoding="utf-8")
    if STEP07_MARKER not in step7 and "STEP 07 STATIC/API PASS" not in step7:
        fail("scripts/e2e-step-07.ps1 is not the expected Step 07 shape")

    existing = [rel for rel in MARKERS if (root / rel).exists()]
    if existing and not args.resume and not args.force:
        fail(
            "Step 08 appears partially/already applied. Refusing to overwrite. "
            "Use --resume for an interrupted matching Step 08, or --force only "
            "if you intentionally want to replace differing generated Step 08 files. "
            "Existing markers: " + ", ".join(existing)
        )

    # Validate all existing generated files before any mutation. This is what
    # makes --resume safe: a partially applied generator cannot silently merge
    # into an unexpected source shape.
    if args.resume and not args.force:
        differences = []
        for rel, expected in FILES.items():
            path = root / rel
            if path.exists():
                if not path.is_file():
                    differences.append(f"{rel}: expected a regular file")
                    continue
                actual = path.read_text(encoding="utf-8")
                if actual != expected:
                    differences.append(f"{rel}: existing content differs")
        if differences:
            fail(
                "Step 08 resume validation failed. No files were changed.\n  - "
                + "\n  - ".join(differences)
                + "\nUse --force only after reviewing the differences."
            )


