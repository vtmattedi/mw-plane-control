def write_file(
    root: Path,
    rel: str,
    content: str,
    backup_dir: Path,
    force: bool,
) -> None:
    path = root / rel
    if path.exists():
        if not path.is_file():
            fail(f"cannot write Step 08 file because path is not a file: {rel}")
        actual = path.read_text(encoding="utf-8")
        if actual == content:
            print(f"unchanged: {rel}")
            return
        if not force:
            fail(
                f"existing Step 08 file differs: {rel}. "
                "No overwrite performed; use --force only after reviewing it."
            )
        backup(root, path, backup_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote: {rel}")


