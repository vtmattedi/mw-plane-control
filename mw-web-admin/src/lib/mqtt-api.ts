import { collectionFrom, controlRequest } from '@/lib/control-api'

export type MqttClient = {
  username: string
  disabled: boolean
  roles: string[]
}

export type MqttRoleAcl = {
  type: string
  topic: string
  allow: boolean
  priority: number
}

export type MqttRole = { name: string; acls: MqttRoleAcl[] }

export type MqttRoles = { roles: MqttRole[]; assignable: string[] }

export type MqttStatsGroup = Record<string, number>

export type MqttStats = {
  available: boolean
  stale: boolean
  updatedAt?: string
  version?: string
  uptimeSeconds?: number
  clients: MqttStatsGroup
  store: MqttStatsGroup
  messages: MqttStatsGroup
  bytes: MqttStatsGroup
  load: MqttStatsGroup
  memory: MqttStatsGroup
}

export type MqttServerStatus = {
  brokerConnected: boolean
  dynsecReachable: boolean
  clients?: number
}

/** A generated broker credential. It is returned once and never stored. */
export type MqttCredential = { username: string; password: string }

/**
 * Every mutation is a small serialisable description so it can be replayed after an
 * Identity step-up round trip. It never carries a secret: passwords are generated by the
 * service and only ever flow back to the browser.
 */
export type MqttOperation =
  | { kind: 'create'; username: string; role?: string }
  | { kind: 'rotate'; username: string }
  | { kind: 'enable'; username: string }
  | { kind: 'disable'; username: string }
  | { kind: 'delete'; username: string }

export const mqttUsernamePattern = /^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$/

const text = (value: unknown) => (typeof value === 'string' ? value : '')

function numbers(value: unknown): MqttStatsGroup {
  const out: MqttStatsGroup = {}
  if (value && typeof value === 'object') {
    for (const [key, entry] of Object.entries(value)) {
      if (typeof entry === 'number' && Number.isFinite(entry)) out[key] = entry
    }
  }
  return out
}

export async function fetchMqttClients(): Promise<MqttClient[]> {
  const body = await controlRequest<unknown>('/mqtt/clients')
  return collectionFrom(body, 'clients')
    .map((row) => ({
      username: text(row.username),
      disabled: row.disabled === true,
      roles: Array.isArray(row.roles)
        ? row.roles.filter((role): role is string => typeof role === 'string')
        : [],
    }))
    .filter((client) => client.username !== '')
}

export async function fetchMqttRoles(): Promise<MqttRoles> {
  const body = (await controlRequest<unknown>('/mqtt/roles')) as Record<
    string,
    unknown
  > | null
  return {
    roles: collectionFrom(body, 'roles').map((row) => ({
      name: text(row.name),
      acls: collectionFrom(row, 'acls').map((acl) => ({
        type: text(acl.type),
        topic: text(acl.topic),
        allow: acl.allow === true,
        priority: typeof acl.priority === 'number' ? acl.priority : 0,
      })),
    })),
    assignable: Array.isArray(body?.assignable)
      ? body.assignable.filter(
          (role): role is string => typeof role === 'string',
        )
      : [],
  }
}

export async function fetchMqttStats(): Promise<MqttStats> {
  const body = ((await controlRequest<unknown>('/mqtt/stats')) ?? {}) as Record<
    string,
    unknown
  >
  return {
    available: body.available === true,
    stale: body.stale === true,
    updatedAt: text(body.updatedAt) || undefined,
    version: text(body.version) || undefined,
    uptimeSeconds:
      typeof body.uptimeSeconds === 'number' ? body.uptimeSeconds : undefined,
    clients: numbers(body.clients),
    store: numbers(body.store),
    messages: numbers(body.messages),
    bytes: numbers(body.bytes),
    load: numbers(body.load),
    memory: numbers(body.memory),
  }
}

export async function fetchMqttServer(): Promise<MqttServerStatus> {
  const body = ((await controlRequest<unknown>('/mqtt/server')) ??
    {}) as Record<string, unknown>
  return {
    brokerConnected: body.brokerConnected === true,
    dynsecReachable: body.dynsecReachable === true,
    clients: typeof body.clients === 'number' ? body.clients : undefined,
  }
}

function credentialFrom(
  body: unknown,
  username: string,
): MqttCredential | null {
  const record = (body ?? {}) as Record<string, unknown>
  const password = text(record.password)
  return password
    ? { username: text(record.username) || username, password }
    : null
}

/** Runs one operation and returns the generated credential, when there is one. */
export async function runMqttOperation(
  operation: MqttOperation,
): Promise<MqttCredential | null> {
  const user = encodeURIComponent(operation.username)
  switch (operation.kind) {
    case 'create': {
      const body = await controlRequest<unknown>('/mqtt/clients', {
        method: 'POST',
        body: JSON.stringify({
          username: operation.username,
          ...(operation.role ? { role: operation.role } : {}),
        }),
      })
      return credentialFrom(body, operation.username)
    }
    case 'rotate': {
      const body = await controlRequest<unknown>(
        `/mqtt/clients/${user}/password`,
        { method: 'POST' },
      )
      return credentialFrom(body, operation.username)
    }
    case 'enable':
    case 'disable':
      await controlRequest<unknown>(`/mqtt/clients/${user}/${operation.kind}`, {
        method: 'POST',
      })
      return null
    case 'delete':
      await controlRequest<unknown>(`/mqtt/clients/${user}`, {
        method: 'DELETE',
      })
      return null
  }
}

/** True when every role of the client may be managed through this UI. */
export function isManageable(client: MqttClient, assignable: string[]) {
  return (
    assignable.length > 0 &&
    client.roles.every((role) => assignable.includes(role))
  )
}
