def backup(root: Path, path: Path, backup_dir: Path) -> None:
    if not path.is_file():
        return
    target = backup_dir / path.relative_to(root)
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.exists():
        shutil.copy2(path, target)


def write_generated(root: Path, rel: str, content: str, backup_dir: Path | None, dry_run: bool, resume: bool) -> None:
    path = root / rel
    if path.exists():
        existing = path.read_text(encoding="utf-8")
        if existing == content:
            print(f"unchanged: {rel}")
            return
        if not resume:
            fail(f"Step 13 generated file already exists with different content: {rel}. Use --resume only after reviewing it.")
        fail(f"--resume refuses differing generated file: {rel}")
    if dry_run:
        print(f"  create: {rel}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote: {rel}")


def replace_once(src: str, old: str, new: str, label: str) -> str:
    count = src.count(old)
    if count != 1:
        fail(f"{label}: expected exactly one source anchor, found {count}")
    return src.replace(old, new, 1)


def patch_router(src: str, service: str) -> str:
    if '"GET /ready"' in src and 'operationalMiddleware(metrics' in src:
        return src
    health = f'''\tmux.HandleFunc(\n\t\t"GET /health",\n\t\thealthHandler("{service}", db),\n\t)\n'''
    insert = health + f'''\tmux.HandleFunc(\n\t\t"GET /ready",\n\t\treadinessHandler("{service}", db),\n\t)\n\n\tmetrics := &operationalMetrics{{}}\n\tstarted := time.Now().UTC()\n\tmux.HandleFunc(\n\t\t"GET /metrics",\n\t\tmetricsHandler("{service}", metrics, started),\n\t)\n'''
    src = replace_once(src, health, insert, f"{service} router health anchor")
    if service == "mw-bff" and '"time"' not in src:
        src = replace_once(src, '"net/http"\n', '"net/http"\n\t"time"\n', "BFF router time import")
    src = replace_once(src, "return securityHeaders(mux)", "return operationalMiddleware(metrics, securityHeaders(mux))", f"{service} router middleware")
    return src


def patch_dockerfile(src: str) -> str:
    if "./cmd/backup-db" not in src:
        builds = '''\nRUN CGO_ENABLED=0 GOOS=linux go build \\\n    -trimpath \\\n    -o /out/backup-db \\\n    ./cmd/backup-db\n\nRUN CGO_ENABLED=0 GOOS=linux go build \\\n    -trimpath \\\n    -o /out/verify-db \\\n    ./cmd/verify-db\n\nRUN CGO_ENABLED=0 GOOS=linux go build \\\n    -trimpath \\\n    -o /out/maintenance \\\n    ./cmd/maintenance\n\nRUN CGO_ENABLED=0 GOOS=linux go build \\\n    -trimpath \\\n    -o /out/config-check \\\n    ./cmd/config-check\n'''
        src = replace_once(src, "\nFROM alpine:3.22\n", builds + "\nFROM alpine:3.22\n", "Dockerfile runtime stage")
    if "COPY --from=build /out/backup-db" not in src:
        copies = '''\nCOPY --from=build /out/backup-db /app/backup-db\nCOPY --from=build /out/verify-db /app/verify-db\nCOPY --from=build /out/maintenance /app/maintenance\nCOPY --from=build /out/config-check /app/config-check\n'''
        src = replace_once(src, "\nUSER app\n", copies + "\nUSER app\n", "Dockerfile USER anchor")
    return src


def patch_gateway(src: str) -> str:
    if "zone=mw_admin:10m" in src and "map $http_x_request_id $mw_request_id" in src:
        return src
    src = replace_once(
        src,
        "    access_log /var/log/nginx/access.log main;\n    error_log /var/log/nginx/error.log warn;",
        "    # Access logs deliberately use $uri from log_format, so query strings are excluded.\n"
        "    access_log /dev/stdout main;\n    error_log /dev/stderr warn;",
        "gateway logging/rate-limit anchor",
    )
    src = replace_once(
        src,
        '    map $http_x_forwarded_proto $mw_forwarded_proto {\n        default $http_x_forwarded_proto;\n        ""      $scheme;\n    }',
        '    map $http_x_forwarded_proto $mw_forwarded_proto {\n        default      $scheme;\n        "~*^https$" https;\n        "~*^http$"  http;\n    }',
        "gateway forwarded-proto map",
    )
    real = '    map $http_x_real_ip $mw_real_ip {\n        default $http_x_real_ip;\n        ""      $remote_addr;\n    }'
    src = replace_once(src, real, real + '\n\n    map $http_x_request_id $mw_request_id {\n        default                         $request_id;\n        "~^[A-Za-z0-9._:-]{1,128}$"   $http_x_request_id;\n    }\n\n    limit_req_zone $mw_real_ip zone=mw_admin:10m rate=30r/s;\n    limit_req_zone $mw_real_ip zone=mw_identity:10m rate=20r/s;\n    limit_req_status 429;', "gateway request-ID/rate-limit map")
    src = replace_once(src, '        add_header X-Frame-Options DENY always;\n\n        location /api/ {', '        add_header X-Frame-Options DENY always;\n        add_header X-Request-ID $mw_request_id always;\n\n        location = /api/metrics {\n            return 404;\n        }\n\n        location /api/ {\n            limit_req zone=mw_admin burst=60 nodelay;', "gateway admin server")
    src = replace_once(src, '        add_header X-Frame-Options DENY always;\n\n        location / {', '        add_header X-Frame-Options DENY always;\n        add_header X-Request-ID $mw_request_id always;\n\n        location = /metrics {\n            return 404;\n        }\n\n        location / {\n            limit_req zone=mw_identity burst=60 nodelay;', "gateway Identity server")
    src = src.replace("proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;", "proxy_set_header X-Forwarded-For $mw_real_ip;")
    marker = "            proxy_set_header X-Forwarded-Proto $mw_forwarded_proto;"
    if src.count(marker) != 2:
        fail("gateway expected two forwarded-proto proxy headers")
    src = src.replace(marker, marker + "\n            proxy_set_header X-Request-ID $mw_request_id;\n            proxy_hide_header X-Request-ID;")
    return src


