def patch_dockerignore(src: str) -> str:
    lines = {line.strip() for line in src.splitlines()}
    if "backups" in lines or "backups/" in lines:
        return src
    return src.rstrip() + "\nbackups\n"

def patch_gitignore(src: str) -> str:
    if any(line.strip() == "backups/" for line in src.splitlines()):
        return src
    return src.rstrip() + "\n\nbackups/\n"


def patch_file(root: Path, rel: str, transform, backup_dir: Path | None, dry_run: bool) -> None:
    path = root / rel
    original = path.read_text(encoding="utf-8")
    updated = transform(original)
    if updated == original:
        print(f"unchanged: {rel}")
        return
    if dry_run:
        print(f"  patch: {rel}")
        return
    assert backup_dir is not None
    backup(root, path, backup_dir)
    path.write_text(updated, encoding="utf-8", newline="\n")
    print(f"patched: {rel}")


def validate(root: Path, parsed: argparse.Namespace) -> None:
    missing = [rel for rel in REQUIRED if not (root / rel).is_file()]
    if missing:
        fail("run from the applied Step 12 mw-plane-control root; missing: " + ", ".join(missing))
    roadmap = (root / "docs/implementation-roadmap.md").read_text(encoding="utf-8")
    if ROADMAP_MARKER not in roadmap:
        fail("docs/implementation-roadmap.md does not contain the canonical Step 13 section")
    sqlite_text = (root / "mw-identity/internal/store/sqlite/sqlite.go").read_text(encoding="utf-8")
    for invariant in ["PRAGMA foreign_keys = ON", "PRAGMA busy_timeout = 5000", "PRAGMA journal_mode = WAL"]:
        if invariant not in sqlite_text:
            fail("Step 13 requires the existing SQLite invariant: " + invariant)
    if not parsed.resume and (root / STEP13_MARKER).exists():
        fail("Step 13 already appears applied. Use --resume to verify/idempotently continue it.")


def format_go(root: Path) -> None:
    go_files = [rel for rel in FILES if rel.endswith(".go")]
    go_files += ["mw-identity/internal/httpapi/router.go", "mw-bff/internal/httpapi/router.go"]
    by_module: dict[str, list[str]] = {"mw-identity": [], "mw-bff": []}
    for rel in go_files:
        module, remainder = rel.split("/", 1)
        by_module[module].append(remainder)
    for module, paths in by_module.items():
        run(["gofmt", "-w", *paths], root / module)


